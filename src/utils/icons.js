export function getIconPath(name) {
  return ICON_PATHS[name] || ''
}

export function renderIconSvg(name, extraClass = '') {
  const path = getIconPath(name) || mdiMapMarker
  const cls = extraClass ? `mdi base-icon ${extraClass}` : 'mdi base-icon'
  return `<svg class="${cls}" viewBox="0 0 24 24" aria-hidden="true"><path d="${path}" fill="currentColor" /></svg>`
}
